"""docs/MEASURED.md, written from one results file. Every number names the command and file it came from."""

from __future__ import annotations

from pathlib import Path

from ..config import REPO_ROOT

COMMAND = "python -m lafaz.eval"


def _fmt(value, unit: str = "") -> str:
    return "n/a" if value is None else f"{value}{unit}"


def _give_up(g: dict) -> str:
    if not g["tasks"]:
        return "not measured: no task in this run is meant to stop"
    return f"{g['mean']} of 2 over {g['tasks']} tasks"


def _rel(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return path.name


def render(result: dict, results_path: Path) -> str:
    s = result["summary"]
    src = _rel(results_path)
    regen = f"`{COMMAND} --report {src}`"
    lines = [
        "# Measured",
        "",
        f"Generated by `{COMMAND}` from `{src}`. Do not edit by hand: run the command again, or {regen} to rewrite",
        "this page from the same file without new model calls.",
        "",
        f"- Run: {result['started']} to {result['finished']} (UTC), commit `{result['commit']}`",
        f"- Model: `{result['model']}` (effort `{result['effort']}`), prices from `config/prices.json`"
        f" ({result['prices_source']})",
        f"- Tasks: {s['tasks']} from `evals/tasks/`, each in its own empty database, nothing approved by a person",
        "",
        "## The four measures",
        "",
        "| Measure | Result | How it is counted |",
        "|---|---|---|",
        f"| Task success | {s['task_success']['passed']} of {s['tasks']} ({_fmt(s['task_success']['pct'], '%')}) |"
        " every expected item, correction, question, conflict, required tool and stop matched, no constraint broken |",
        f"| Path quality | mean {_fmt(s['path_quality']['mean_ratio'])}x, worst {_fmt(s['path_quality']['max_ratio'])}x,"
        f" {s['path_quality']['repeated_calls']} repeated calls | tool steps used / the task's minimum steps |",
        f"| Constraint adherence | {s['constraint_violations']} violations ({s['approvals_pending']} actions left"
        " waiting for a person) | irreversible actions that ran without a person's approval; must be 0 |",
        f"| Give-up quality | {_give_up(s['give_up_quality'])} |"
        " only tasks meant to stop: 2 = stopped for an allowed reason and said why |",
        "",
        "## By category",
        "",
        "| Category | Passed |",
        "|---|---|",
    ]
    lines += [f"| {k} | {v['passed']} of {v['tasks']} |" for k, v in s["by_category"].items()]
    lines += [
        "",
        "## Supporting numbers",
        "",
        f"- Items rejected by the quote checker: {s['quotes_rejected']['count']}",
        f"- Self-corrections resolved to the newer words: {s['corrections']['resolved']} of"
        f" {s['corrections']['expected']} (marked as a correction by the model: {s['corrections']['flagged']})",
        f"- Latency per run: p50 {_fmt(s['latency_ms']['p50'], ' ms')}, p95 {_fmt(s['latency_ms']['p95'], ' ms')}",
        f"- Cost per run: mean USD {_fmt(s['cost_usd']['mean'])}, all runs USD {_fmt(s['cost_usd']['total'])}",
        f"- Runs that crashed: {len(s['crashed'])}" + (f" ({', '.join(s['crashed'])})" if s["crashed"] else ""),
        "",
    ]
    if s["quotes_rejected"]["examples"]:
        lines += ["Examples of rejected items (the quote was not in the input):", ""]
        lines += [f"- `{e['task']}`: \"{e['text']}\" ({e['reason']})" for e in s["quotes_rejected"]["examples"]]
        lines.append("")
    lines += ["## Every task", "", "| Task | Category | Result | Stop | Steps | Cost USD | ms |", "|---|---|---|---|---|---|---|"]
    for r in result["tasks"]:
        verdict = "pass" if r["success"] else "fail: " + ", ".join(k for k, ok in r["checks"].items() if not ok)
        lines.append(f"| `{r['id']}` | {r['category']} | {verdict} | {r['reason']} | {r['steps_used']}/{r['min_steps']}"
                     f" | {r['cost_usd']} | {r['ms']} |")
    lines.append("")
    return "\n".join(lines)


def write(result: dict, results_path: Path, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(result, results_path), encoding="utf-8")
